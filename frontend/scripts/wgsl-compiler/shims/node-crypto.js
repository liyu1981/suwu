function rotr(x, n) {
  return (x >>> n) | (x << (32 - n));
}

export function utf8Bytes(str) {
  const out = new Uint8Array(str.length * 3);
  let j = 0;
  for (let i = 0; i < str.length; i++) {
    let cp = str.charCodeAt(i);
    if (cp >= 0xd800 && cp <= 0xdbff) {
      const next = i + 1 < str.length ? str.charCodeAt(i + 1) : 0;
      if (next >= 0xdc00 && next <= 0xdfff) {
        cp = 0x10000 + ((cp - 0xd800) << 10) + (next - 0xdc00);
        i++;
      } else cp = 0xfffd;
    } else if (cp >= 0xdc00 && cp <= 0xdfff) cp = 0xfffd;
    if (cp < 0x80) out[j++] = cp;
    else if (cp < 0x800) {
      out[j++] = 0xc0 | (cp >> 6);
      out[j++] = 0x80 | (cp & 63);
    } else if (cp < 0x10000) {
      out[j++] = 0xe0 | (cp >> 12);
      out[j++] = 0x80 | ((cp >> 6) & 63);
      out[j++] = 0x80 | (cp & 63);
    } else {
      out[j++] = 0xf0 | (cp >> 18);
      out[j++] = 0x80 | ((cp >> 12) & 63);
      out[j++] = 0x80 | ((cp >> 6) & 63);
      out[j++] = 0x80 | (cp & 63);
    }
  }
  return out.subarray(0, j);
}

function sha256Bytes(bytes) {
  const H = new Int32Array([
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab,
    0x5be0cd19,
  ]);
  const len = bytes.length;
  const padded = new Uint8Array((((len + 8) >> 6) + 1) << 6);
  padded.set(bytes);
  padded[len] = 0x80;
  const view = new DataView(padded.buffer);
  view.setUint32(padded.length - 8, Math.floor((len * 8) / 0x100000000), false);
  view.setUint32(padded.length - 4, (len * 8) >>> 0, false);

  const w = new Int32Array(64);
  for (let off = 0; off < padded.length; off += 64) {
    for (let i = 0; i < 16; i++) w[i] = view.getInt32(off + i * 4, false);
    for (let i = 16; i < 64; i++) {
      const w15 = w[i - 15];
      const w2 = w[i - 2];
      const s0 = rotr(w15, 7) ^ rotr(w15, 18) ^ (w15 >>> 3);
      const s1 = rotr(w2, 17) ^ rotr(w2, 19) ^ (w2 >>> 10);
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) | 0;
    }
    let a = H[0];
    let b = H[1];
    let c = H[2];
    let d = H[3];
    let e = H[4];
    let f = H[5];
    let g = H[6];
    let h = H[7];
    for (let i = 0; i < 64; i++) {
      const S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const t1 = (h + S1 + ch + K[i] + w[i]) | 0;
      const S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + maj) | 0;
      h = g;
      g = f;
      f = e;
      e = (d + t1) | 0;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) | 0;
    }
    H[0] = (H[0] + a) | 0;
    H[1] = (H[1] + b) | 0;
    H[2] = (H[2] + c) | 0;
    H[3] = (H[3] + d) | 0;
    H[4] = (H[4] + e) | 0;
    H[5] = (H[5] + f) | 0;
    H[6] = (H[6] + g) | 0;
    H[7] = (H[7] + h) | 0;
  }
  let hex = '';
  for (let i = 0; i < 8; i++) hex += (H[i] >>> 0).toString(16).padStart(8, '0');
  return hex;
}

export function createHash(algo) {
  if (algo !== 'sha256') throw new Error(`node:crypto shim supports only sha256, got ${algo}`);
  let text = '';
  return {
    update(data) {
      text += typeof data === 'string' ? data : String(data);
      return this;
    },
    digest(enc) {
      const hex = sha256Bytes(utf8Bytes(text));
      return enc === 'hex' ? hex : hex;
    },
  };
}
