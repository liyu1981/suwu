// `node:crypto` shim: only `createHash('sha256')` is used (cache keys and
// mangle prefixes by the resolver). Any deterministic digest is sufficient for
// correctness — the digest never leaves the artifact — but sha256 is cheap and
// collision-resistant, matching Node's behaviour.

